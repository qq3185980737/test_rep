void jab_for_MOZYME(int ia, int ja, const double* pja, const double* pjb,
                    const double* w, double* f1, double* f2) {
    double suma[11]={}, sumb[11]={};
    for (int j=1;j<=16;++j)
        for (int i=1;i<=10;++i) {
            suma[i]+=pja[j]*w[jindx[i][j]];
            sumb[i]+=pjb[j]*w[jjndx[i][j]];
        }
    int i=0;
    for (int i5=1;i5<=4;++i5) {
        int iia=ia+i5-1, ija=ja+i5-1;
        int ioff=(iia*(iia-1))/2+ia-1;
        int joff=(ija*(ija-1))/2+ja-1;
        for (int i6=1;i6<=i5;++i6) {
            ++ioff; ++joff; ++i;
            f1[ioff]+=sumb[i];
            f2[joff]+=suma[i];
        }
    }
}
