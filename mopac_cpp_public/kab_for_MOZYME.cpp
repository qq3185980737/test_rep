void kab_for_MOZYME(int ia, int ja, const double* pk, const double* w, double* f) {
    double sum[17]={};
    for (int j=1;j<=16;++j)
        for (int i=1;i<=16;++i)
            sum[j] += pk[i]*w[kb[j][i]];
    if (ia > ja) {
        int m=0;
        for (int j1=ia; j1<=ia+3; ++j1) {
            int j=(j1*(j1-1))/2;
            for (int j2=ja; j2<=ja+3; ++j2) { ++m; f[j+j2]-=sum[m]; }
        }
    } else if (ia < ja) {
        int m=0;
        for (int j1=ia; j1<=ia+3; ++j1)
            for (int j2=ja; j2<=ja+3; ++j2) {
                ++m;
                int j3=(j2*(j2-1))/2+j1;
                f[j3]-=sum[m];
            }
    } else {
        for (int i=1;i<=16;++i) f[i]-=sum[i]*0.5;
    }
}
